#!/usr/bin/env python3
"""Engine/ContextData.h (D63): how often one Vietnamese syllable follows another in real text, so a typo fix can
pick the word that fits after the previous one ("dự" + đoán, not đón).
Input: pairs TSV "prev\\tnext\\tcount" and its unigram TSV "word\\tcount" (lowercase, NFC), counted from the
Vietnamese news corpus github.com/lingskr/Vietnamese-Corpus-and-Dictionary (VNTC), every 10th file left out for tests.
Only syllables in vi_50k.txt; pairs seen MIN+ times. Words are ids into a sorted list; a pair is id1 << 16 | id2."""
import os, sys, math, unicodedata
pairs, unis = sys.argv[1], sys.argv[2]
MIN = int(os.environ.get('VIKEY_CONTEXT_MIN', '5'))
here = os.path.dirname(os.path.abspath(__file__))
V = set(l.split()[0] for l in open(os.path.join(here, 'vi_50k.txt'), encoding='utf-8'))
TONES = {'\u0300': 'f', '\u0301': 's', '\u0309': 'r', '\u0303': 'x', '\u0323': 'j'}
def telex(w):   # canonical Telex keys, tone key last: "đoán" -> "ddoans"
    keys, tone = '', ''
    for ch in w:
        d = unicodedata.normalize('NFD', ch); base, marks = d[0], d[1:]
        if base == 'đ': keys += 'dd'; continue
        k = base
        for m in marks:
            if m in TONES: tone = TONES[m]
            elif m == '\u0302': k += base
            elif m in '\u0306\u031b': k += 'w'
            else: return None
        keys += k
    return keys + tone
uni = {}
for l in open(unis, encoding='utf-8'):
    w, c = l.rstrip('\n').split('\t')
    k = telex(w)
    if w in V and int(c) >= MIN and k and k.isascii() and k.isalpha(): uni[w] = int(c)   # Telex keys only (not 'ð')
total = sum(uni.values())
P = []
for l in open(pairs, encoding='utf-8'):
    a, b, c = l.rstrip('\n').split('\t')
    if int(c) >= MIN and a in uni and b in uni: P.append((a, b, int(c)))
words = sorted(uni, key=lambda w: w.encode('utf-8'))
idx = {w: i for i, w in enumerate(words)}
assert len(words) < 65536
packed = sorted((idx[a] << 16 | idx[b], c) for a, b, c in P)
lg = lambda v: min(255, round(8 * math.log2(v)))
def arr(f, ctype, name, values):   # numbers, 32 a line: MSVC takes neither a string literal over 64 KB nor very long lines
    values = list(values)
    f.write(f'static const {ctype} {name}[{len(values)}] = {{\n')
    for i in range(0, len(values), 32): f.write('    ' + ','.join(map(str, values[i:i + 32])) + ',\n')
    f.write('};\n')
KEYS = {w: telex(w) for w in words}
out = os.path.join(here, '..', '..', 'Engine', 'ContextData.h')
with open(out, 'w') as f:
    f.write('// Generated by Tools/autoswitch/build_context.py. Do not edit. Syllable pairs for typo fixes (D63).\n')
    f.write('// Source: Vietnamese news (VNTC, via github.com/lingskr/Vietnamese-Corpus-and-Dictionary), counts only.\n')
    f.write('#ifndef ContextData_h\n#define ContextData_h\n')
    blob, offs = b'', []
    for w in words: offs.append(len(blob)); blob += w.encode('utf-8') + b'\0'
    arr(f, 'char', 'kCtxWords', [b if b < 128 else b - 256 for b in blob + b'\0'])   # UTF-8, each word ends in 0 (and one more, as a string)
    arr(f, 'unsigned int', 'kCtxWordOffsets', offs)
    arr(f, 'unsigned char', 'kCtxWordLog', (lg(uni[w]) for w in words))
    f.write(f'static const int kCtxWordCount = {len(words)};\n')
    blob, koffs = b'', []
    for w in words: koffs.append(len(blob)); blob += KEYS[w].encode() + b'\0'
    arr(f, 'char', 'kCtxWordKeys', blob + b'\0')   # Telex keys of each word, same order, tone key last
    arr(f, 'unsigned int', 'kCtxWordKeyOffsets', koffs)
    arr(f, 'unsigned int', 'kCtxPairs', (k for k, _ in packed))
    arr(f, 'unsigned char', 'kCtxPairLog', (lg(c) for _, c in packed))
    f.write(f'static const int kCtxPairCount = {len(packed)};\nstatic const double kCtxTotal = {total}.0;\n#endif\n')
print(len(words), 'words', len(packed), 'pairs ->', os.path.normpath(out), os.path.getsize(out), 'bytes')
